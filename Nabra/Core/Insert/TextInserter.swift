import AppKit
import Carbon.HIToolbox

/// Puts text at the cursor of whatever app is in front.
final class TextInserter {
    /// Everything on the clipboard, so it can be put back after pasting.
    private struct ClipboardContents {
        let items: [[NSPasteboard.PasteboardType: Data]]

        init?(_ pasteboard: NSPasteboard) {
            var total = 0
            var captured: [[NSPasteboard.PasteboardType: Data]] = []
            for item in pasteboard.pasteboardItems ?? [] {
                var entry: [NSPasteboard.PasteboardType: Data] = [:]
                for type in item.types {
                    guard let data = item.data(forType: type) else { continue }
                    total += data.count
                    // Very large clipboards (big images, files) are not worth copying around.
                    if total > 40_000_000 { return nil }
                    entry[type] = data
                }
                if !entry.isEmpty { captured.append(entry) }
            }
            items = captured
        }

        func restore(to pasteboard: NSPasteboard) {
            pasteboard.clearContents()
            let restored = items.map { entry -> NSPasteboardItem in
                let item = NSPasteboardItem()
                for (type, data) in entry { item.setData(data, forType: type) }
                return item
            }
            if !restored.isEmpty { pasteboard.writeObjects(restored) }
        }
    }

    private var pendingRestore: (contents: ClipboardContents, changeCount: Int)?
    private var restoreWork: DispatchWorkItem?
    private let restoreDelay: TimeInterval = 0.8

    /// Inserts `text`. Must be called on the main thread. Returns false when events could not be posted.
    @discardableResult
    func insert(_ text: String, method: InsertionMethod, restoreClipboard: Bool) -> Bool {
        guard !text.isEmpty else { return true }
        switch method {
        case .paste: return paste(text, restoreClipboard: restoreClipboard)
        case .type: return type(text)
        }
    }

    /// Copies text to the clipboard without pasting.
    func copy(_ text: String) {
        cancelPendingRestore()
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    // MARK: - Paste

    private func paste(_ text: String, restoreClipboard: Bool) -> Bool {
        let pasteboard = NSPasteboard.general
        // If an earlier restore is still pending, keep that original clipboard rather than our own text.
        let original: ClipboardContents?
        if let pending = pendingRestore, pasteboard.changeCount == pending.changeCount {
            original = pending.contents
        } else {
            original = restoreClipboard ? ClipboardContents(pasteboard) : nil
        }
        restoreWork?.cancel()
        restoreWork = nil
        pendingRestore = nil

        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        if restoreClipboard {
            // Tell clipboard managers this entry is temporary (nspasteboard.org conventions).
            pasteboard.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
            pasteboard.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        }
        let ourChange = pasteboard.changeCount

        let keyCode = KeyboardLayout.keyCode(for: "v", fallback: UInt16(kVK_ANSI_V))
        guard postKey(keyCode, flags: .maskCommand) else { return false }

        if restoreClipboard, let original {
            pendingRestore = (original, ourChange)
            let work = DispatchWorkItem { [weak self] in
                guard let self, let pending = self.pendingRestore else { return }
                self.pendingRestore = nil
                // Only put the old clipboard back if nothing else has been copied meanwhile.
                if NSPasteboard.general.changeCount == pending.changeCount {
                    pending.contents.restore(to: NSPasteboard.general)
                }
            }
            restoreWork = work
            DispatchQueue.main.asyncAfter(deadline: .now() + restoreDelay, execute: work)
        }
        return true
    }

    private func cancelPendingRestore() {
        restoreWork?.cancel()
        restoreWork = nil
        pendingRestore = nil
    }

    // MARK: - Typing

    private func type(_ text: String) -> Bool {
        guard let source = CGEventSource(stateID: .combinedSessionState) else { return false }
        let units = Array(text.utf16)
        var index = 0
        while index < units.count {
            var end = min(index + 16, units.count)
            // Do not split a surrogate pair.
            if end < units.count, UTF16.isLeadSurrogate(units[end - 1]) { end -= 1 }
            let chunk = Array(units[index..<end])
            guard let down = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: true),
                  let up = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: false)
            else { return false }
            down.flags = []
            up.flags = []
            down.keyboardSetUnicodeString(stringLength: chunk.count, unicodeString: chunk)
            up.keyboardSetUnicodeString(stringLength: chunk.count, unicodeString: chunk)
            down.setIntegerValueField(.eventSourceUserData, value: HotkeyMonitor.syntheticEventMarker)
            up.setIntegerValueField(.eventSourceUserData, value: HotkeyMonitor.syntheticEventMarker)
            down.post(tap: .cgSessionEventTap)
            up.post(tap: .cgSessionEventTap)
            usleep(2500)
            index = end
        }
        return true
    }

    private func postKey(_ keyCode: UInt16, flags: CGEventFlags) -> Bool {
        guard let source = CGEventSource(stateID: .combinedSessionState),
              let down = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: false)
        else { return false }
        down.flags = flags
        up.flags = flags
        down.setIntegerValueField(.eventSourceUserData, value: HotkeyMonitor.syntheticEventMarker)
        up.setIntegerValueField(.eventSourceUserData, value: HotkeyMonitor.syntheticEventMarker)
        down.post(tap: .cgSessionEventTap)
        up.post(tap: .cgSessionEventTap)
        return true
    }
}

/// Adjusts dictated text so it joins the text already in the field naturally.
enum InsertionFormatter {
    private static let lowercaseStarters: Set<String> = [
        "the", "a", "an", "and", "but", "so", "or", "it", "this", "that", "these", "those", "we", "you", "he", "she",
        "they", "is", "are", "was", "were", "in", "on", "at", "to", "for", "with", "of", "my", "our", "your", "their",
        "if", "when", "then", "also", "just", "because", "as", "by", "from", "there", "here", "what", "which", "who",
        "how", "why", "not", "no", "yes", "let's", "can", "could", "should", "would", "will", "do", "does", "did",
        "have", "has", "had", "please", "thanks", "okay", "well", "maybe", "now", "some", "all", "any", "each",
    ]
    private static let openers: Set<Character> = ["(", "[", "{", "\"", "“", "‘", "'", "«", "/", "@", "#", "-", "—", "_"]

    /// Adds spacing and fixes the first letter's case based on the characters around the cursor.
    static func format(_ text: String, context: FocusSnapshot, enabled: Bool) -> String {
        guard enabled, !text.isEmpty else { return text }
        guard context.hasTextContext else {
            // Nothing known about the field: a trailing space lets the next dictation continue cleanly.
            return text.hasSuffix("\n") ? text : text + " "
        }
        var result = text
        if let before = context.precedingCharacter {
            let midSentence = before.isLetter || before.isNumber || before == "," || before == "،" || before == ";"
            if midSentence { result = lowercasedStartIfCommonWord(result) }
            let needsSpace = !before.isWhitespace && !before.isNewline && !openers.contains(before)
            if SpokenLists.startsWithList(result), !before.isNewline {
                // A list dictated after text on the same line starts on a line of its own.
                result = "\n" + result
            } else if needsSpace, let first = result.first, !first.isWhitespace, !",.!?;:،؛؟)]}%".contains(first) {
                result = " " + result
            }
        }
        if let after = context.followingCharacter, after.isLetter || after.isNumber {
            result += " "
        }
        return result
    }

    private static func lowercasedStartIfCommonWord(_ text: String) -> String {
        guard let first = text.first, first.isUppercase, first.isASCII else { return text }
        let word = String(text.prefix { $0.isLetter || $0 == "'" || $0 == "’" })
        guard word.count > 1 || word == "A" else { return text }
        // Leave acronyms and names alone; only relax ordinary sentence starters.
        guard word.dropFirst().allSatisfy(\.isLowercase), lowercaseStarters.contains(word.lowercased()) else { return text }
        return first.lowercased() + text.dropFirst()
    }
}
